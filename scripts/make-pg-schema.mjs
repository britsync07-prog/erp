import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

/**
 * Generates the production Prisma schema from the development one.
 *
 *   node scripts/make-pg-schema.mjs
 *
 * Why this exists: `prisma migrate deploy` replays the migration files that
 * sit next to the schema, and the committed migrations are SQLite DDL
 * (AUTOINCREMENT, PRAGMA …) that PostgreSQL cannot execute. Rather than
 * hand-maintaining a second datamodel that can drift, the Postgres schema is
 * derived mechanically from `prisma/schema.prisma` — one source of truth.
 *
 * Output: prisma/postgres/schema.prisma  (provider = "postgresql")
 * Its migrations live in prisma/postgres/migrations and are generated once via
 *   npx prisma migrate diff --from-empty \
//     --to-schema-datamodel prisma/postgres/schema.prisma --script
 */
const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const src = join(root, "prisma", "schema.prisma");
const out = join(root, "prisma", "postgres", "schema.prisma");

const original = readFileSync(src, "utf8");

const marker = "// ---- GENERATED FILE ----";
const banner = `${marker}
// GENERATED by scripts/make-pg-schema.mjs — do not edit by hand.
// Source of truth: prisma/schema.prisma (SQLite, used for local dev).
// Identical datamodel, PostgreSQL provider.
`;

let next = original.replace(
  /provider\s*=\s*"sqlite"/,
  'provider = "postgresql"',
);

if (next === original) {
  // Already generated and in sync.
  process.exit(0);
}

mkdirSync(dirname(out), { recursive: true });
// No BOM: the Prisma CLI is strict about the first bytes of a schema file.
writeFileSync(out, banner + next, "utf8");
console.log(`Wrote ${out}`);